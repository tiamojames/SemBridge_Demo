"""Build waveform previews from the exact WAV files used on the demo page."""

import array
import hashlib
import json
import sys
import wave
from html.parser import HTMLParser
from pathlib import Path


class AudioSources(HTMLParser):
    def __init__(self):
        super().__init__()
        self.sources = set()

    def handle_starttag(self, tag, attrs):
        if tag == "audio":
            self.sources.add(dict(attrs)["src"])


root = Path(__file__).resolve().parents[1]
parser = AudioSources()
parser.feed((root / "index.html").read_text())
result = {}
for src in sorted(parser.sources):
    path = root / src
    with wave.open(str(path), "rb") as audio:
        width = audio.getsampwidth()
        frames = audio.getnframes()
        channels = audio.getnchannels()
        duration = frames / audio.getframerate()
        raw = audio.readframes(frames)
        if width in (2, 4):
            samples = array.array("h" if width == 2 else "i", raw)
            if sys.byteorder != "little":
                samples.byteswap()
        elif width == 3:
            samples = array.array("i", (int.from_bytes(raw[i:i + 3], "little", signed=True)
                                        for i in range(0, len(raw), 3)))
        elif width == 1:
            samples = array.array("h", (value - 128 for value in raw))
        else:
            raise ValueError(f"Unsupported PCM width {width}: {src}")
    # Peak envelopes use all channels without changing the published audio.
    peaks = []
    for index in range(128):
        start = (index * frames // 128) * channels
        end = ((index + 1) * frames // 128) * channels
        peaks.append(max((abs(value) for value in samples[start:end]), default=0))
    peak = max(max(peaks), 1)
    result[src] = {
        "duration": round(duration, 3),
        "peaks": [round(value / peak, 3) for value in peaks],
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
    }
(root / "js/audio-data.js").write_text(
    "// Generated by scripts/build_audio_data.py from published WAV assets.\n"
    + "window.SEMBRIDGE_AUDIO = " + json.dumps(result, separators=(",", ":")) + ";\n"
)
print(f"Built real waveform previews for {len(result)} audio files.")
